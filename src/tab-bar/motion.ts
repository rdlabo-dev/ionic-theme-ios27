// Native platter release: qDD5O2 normalized displacement fits w=17.5/s,
// damping=.6, onset=1/60s (RMS ratio error <.001). Continue the press during
// that observed onset, then retain its velocity. This avoids replaying a 66ms
// platter-release recording for a 150ms press.
export const platterRelease = (held: number, seconds: number): number => {
  const delay = 1 / 60;
  if (seconds >= 0.367) return 0;
  const press = (t: number) => sample(transfer, t)[3];
  if (seconds <= delay) return press(held + seconds);
  const at = held + delay;
  const value = press(at);
  const velocity = (press(at + 0.001) - press(at - 0.001)) / 0.002;
  const t = seconds - delay;
  const omega = 17.5;
  const decay = omega * 0.6;
  const damped = omega * 0.8;
  return Math.exp(-decay * t) * (value * Math.cos(damped * t) + ((velocity + decay * value) / damped) * Math.sin(damped * t));
};
