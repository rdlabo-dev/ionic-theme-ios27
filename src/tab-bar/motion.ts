export const sample = (frames: number[][], time: number): number[] => {
  const after = frames.findIndex((frame) => frame[0] >= time);
  if (after <= 0) return frames[after === 0 ? 0 : frames.length - 1].slice(1);
  const a = frames[after - 1];
  const b = frames[after];
  const p = (time - a[0]) / (b[0] - a[0]);
  return a.slice(1).map((value, index) => value + (b[index + 1] - value) * p);
};

